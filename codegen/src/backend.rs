//! Backend: [`IrModel`] -> Rust source files written under an output directory.
//! Schema-agnostic; reused across schema styles.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result};

use crate::ir::*;

const GENERATED_HEADER: &str = "// @generated by codegen — do not edit by hand.\n\n";

pub fn write_model(model: &IrModel, out_dir: &Path) -> Result<()> {
    let module_of: BTreeMap<String, Module> = model
        .types
        .iter()
        .map(|t| (t.name().to_string(), t.module()))
        .collect();

    for sub in ["datatypes", "enumerations", "messages", "helpers"] {
        let dir = out_dir.join(sub);
        if dir.exists() {
            std::fs::remove_dir_all(&dir)?;
        }
        std::fs::create_dir_all(&dir)?;
    }

    let mut datatype_mods: Vec<String> = Vec::new();
    let mut enum_mods: Vec<String> = Vec::new();
    let mut message_mods: Vec<String> = Vec::new();

    // Named types.
    for ty in &model.types {
        let stem = crate::naming::file_stem(ty.name());
        let (imports, body) = match ty {
            IrType::Struct(s) => render_struct(s, &module_of, &model.version),
            IrType::Enum(e) => (BTreeSet::new(), render_enum(e)),
        };
        let file = format!("{GENERATED_HEADER}{}{body}", join_imports(&imports));
        let dir = ty.module().dir();
        std::fs::write(out_dir.join(dir).join(format!("{stem}.rs")), file)?;
        match ty.module() {
            Module::Datatypes => datatype_mods.push(stem),
            Module::Enumerations => enum_mods.push(stem),
        }
    }

    // Messages.
    for msg in &model.messages {
        let mut imports = BTreeSet::new();
        let mut body = String::new();
        if let Some(req) = &msg.request {
            let (imp, b) = render_struct(req, &module_of, &model.version);
            imports.extend(imp);
            body.push_str(&b);
        }
        if let Some(resp) = &msg.response {
            let (imp, b) = render_struct(resp, &module_of, &model.version);
            imports.extend(imp);
            body.push_str(&b);
        }
        let file = format!("{GENERATED_HEADER}{}{body}", join_imports(&imports));
        std::fs::write(
            out_dir
                .join("messages")
                .join(format!("{}.rs", msg.file_stem)),
            file,
        )?;
        message_mods.push(msg.file_stem.clone());
    }

    datatype_mods.sort();
    enum_mods.sort();
    message_mods.sort();

    write_mod_rs(&out_dir.join("datatypes"), &datatype_mods)?;
    write_mod_rs(&out_dir.join("enumerations"), &enum_mods)?;
    write_mod_rs(&out_dir.join("messages"), &message_mods)?;

    write_helpers(model, &out_dir.join("helpers"))?;
    write_version_mod(model, out_dir)?;

    Ok(())
}

fn join_imports(imports: &BTreeSet<String>) -> String {
    if imports.is_empty() {
        return String::new();
    }
    let mut s = String::new();
    for i in imports {
        let _ = writeln!(s, "{i}");
    }
    s.push('\n');
    s
}

fn write_mod_rs(dir: &Path, mods: &[String]) -> Result<()> {
    let mut s = String::from(GENERATED_HEADER);
    for m in mods {
        let _ = writeln!(s, "pub mod {m};");
    }
    s.push('\n');
    // Flattened re-exports so both `module::TypeName` and `dir::TypeName` paths
    // resolve. Type names are unique, so the globs never collide.
    for m in mods {
        let _ = writeln!(s, "pub use {m}::*;");
    }
    std::fs::write(dir.join("mod.rs"), s)
        .with_context(|| format!("writing {}/mod.rs", dir.display()))?;
    Ok(())
}

fn doc_lines(doc: &Option<String>, out: &mut String) {
    if let Some(d) = doc {
        for line in d.lines() {
            let _ = writeln!(out, "/// {}", line.trim_end());
        }
    }
}

fn render_struct(
    s: &IrStruct,
    module_of: &BTreeMap<String, Module>,
    version: &str,
) -> (BTreeSet<String>, String) {
    let mut imports = BTreeSet::new();
    let validate = s.derives_validate();
    if validate {
        imports.insert("use validator::Validate;".to_string());
    }

    let mut fields = String::new();
    for f in &s.fields {
        render_field(f, version, module_of, &mut imports, &mut fields);
    }

    let mut out = String::new();
    doc_lines(&s.doc, &mut out);
    if validate {
        out.push_str(
            "#[derive(serde::Serialize, serde::Deserialize, Debug, Clone, PartialEq, Validate, Default)]\n",
        );
    } else {
        out.push_str(
            "#[derive(serde::Serialize, serde::Deserialize, Debug, Clone, PartialEq, Default)]\n",
        );
    }
    out.push_str("#[serde(rename_all = \"camelCase\")]\n");
    let _ = writeln!(out, "pub struct {} {{", s.name);
    out.push_str(&fields);
    out.push_str("}\n\n");

    let extra = if validate {
        ", validator::Validate"
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "static_assertions::assert_impl_all!({}: serde::Serialize, serde::de::DeserializeOwned, Clone, core::fmt::Debug, PartialEq, Default{extra});\n",
        s.name
    );
    (imports, out)
}

fn render_field(
    f: &IrField,
    version: &str,
    module_of: &BTreeMap<String, Module>,
    imports: &mut BTreeSet<String>,
    out: &mut String,
) {
    doc_lines(&f.doc, out);

    // serde rename
    if let Some(r) = &f.rename {
        let _ = writeln!(out, "    #[serde(rename = \"{r}\")]");
    }

    // serde optional / special-with
    let is_datetime = matches!(base_ref(&f.ty), IrTypeRef::DateTime);
    let is_decimal = matches!(base_ref(&f.ty), IrTypeRef::Number);
    let serde_attr = match (f.optional, is_datetime, is_decimal) {
        (true, true, _) => Some(
            "#[serde(default, skip_serializing_if = \"Option::is_none\", with = \"datetime_rfc3339::option\")]"
                .to_string(),
        ),
        (false, true, _) => Some("#[serde(with = \"datetime_rfc3339\")]".to_string()),
        (true, _, true) => Some(
            "#[serde(default, skip_serializing_if = \"Option::is_none\", with = \"rust_decimal::serde::arbitrary_precision_option\")]"
                .to_string(),
        ),
        (false, _, true) => {
            Some("#[serde(with = \"rust_decimal::serde::arbitrary_precision\")]".to_string())
        }
        (true, false, false) => {
            Some("#[serde(skip_serializing_if = \"Option::is_none\")]".to_string())
        }
        (false, false, false) => None,
    };
    if let Some(a) = serde_attr {
        let _ = writeln!(out, "    {a}");
    }

    // validation
    let mut clauses: Vec<String> = Vec::new();
    if let IrTypeRef::Int { min, max } = base_ref(&f.ty) {
        if min.is_some() || max.is_some() {
            clauses.push(format!("range({})", min_max(*min, *max)));
        }
    }
    for c in &f.constraints {
        match c {
            Constraint::Length { min, max } => {
                clauses.push(format!("length({})", min_max(*min, *max)));
            }
            Constraint::DecimalRange { fn_name } => {
                clauses.push(format!("custom(function = \"{fn_name}\")"));
                imports.insert(format!(
                    "use crate::{version}::helpers::validator::{fn_name};"
                ));
            }
            Constraint::IdentifierString => {
                clauses.push("custom(function = \"validate_identifier_string\")".to_string());
                imports.insert(format!(
                    "use crate::{version}::helpers::validator::validate_identifier_string;"
                ));
            }
        }
    }
    if !clauses.is_empty() {
        let _ = writeln!(out, "    #[validate({})]", clauses.join(", "));
    }

    // imports for the type
    collect_type_imports(&f.ty, version, module_of, imports);

    let rendered = render_type(&f.ty);
    let rendered = if f.optional {
        format!("Option<{rendered}>")
    } else {
        rendered
    };
    let _ = writeln!(out, "    pub {}: {rendered},", f.rust_name);
}

/// The element type ref, unwrapping a single `Array` layer for serde-attr
/// decisions (date-time / decimal arrays don't occur, but keep it robust).
fn base_ref(ty: &IrTypeRef) -> &IrTypeRef {
    ty
}

fn min_max(min: Option<i64>, max: Option<i64>) -> String {
    match (min, max) {
        (Some(a), Some(b)) => format!("min = {a}, max = {b}"),
        (Some(a), None) => format!("min = {a}"),
        (None, Some(b)) => format!("max = {b}"),
        (None, None) => String::new(),
    }
}

fn render_type(ty: &IrTypeRef) -> String {
    match ty {
        IrTypeRef::Named(n) => n.clone(),
        IrTypeRef::Str => "String".to_string(),
        IrTypeRef::Int { min, max } => int_width(*min, *max).to_string(),
        IrTypeRef::Number => "Decimal".to_string(),
        IrTypeRef::Bool => "bool".to_string(),
        IrTypeRef::DateTime => "DateTime<Utc>".to_string(),
        IrTypeRef::Array(inner) => format!("Vec<{}>", render_type(inner)),
    }
}

fn collect_type_imports(
    ty: &IrTypeRef,
    version: &str,
    module_of: &BTreeMap<String, Module>,
    imports: &mut BTreeSet<String>,
) {
    match ty {
        IrTypeRef::Named(n) => {
            if let Some(m) = module_of.get(n) {
                let stem = crate::naming::file_stem(n);
                imports.insert(format!("use crate::{version}::{}::{stem}::{n};", m.dir()));
            }
        }
        IrTypeRef::Number => {
            imports.insert("use rust_decimal::Decimal;".to_string());
        }
        IrTypeRef::DateTime => {
            imports.insert("use chrono::DateTime;".to_string());
            imports.insert("use chrono::Utc;".to_string());
            imports.insert(format!("use crate::{version}::helpers::datetime_rfc3339;"));
        }
        IrTypeRef::Array(inner) => collect_type_imports(inner, version, module_of, imports),
        _ => {}
    }
}

fn int_width(min: Option<i64>, max: Option<i64>) -> &'static str {
    match (min, max) {
        (Some(lo), Some(hi)) if lo >= 0 => {
            if hi <= u8::MAX as i64 {
                "u8"
            } else if hi <= u16::MAX as i64 {
                "u16"
            } else if hi <= u32::MAX as i64 {
                "u32"
            } else {
                "u64"
            }
        }
        (Some(lo), Some(hi)) => {
            if lo >= i8::MIN as i64 && hi <= i8::MAX as i64 {
                "i8"
            } else if lo >= i16::MIN as i64 && hi <= i16::MAX as i64 {
                "i16"
            } else if lo >= i32::MIN as i64 && hi <= i32::MAX as i64 {
                "i32"
            } else {
                "i64"
            }
        }
        (Some(lo), None) if lo >= 0 => "u32",
        _ => "i32",
    }
}

fn render_enum(e: &IrEnum) -> String {
    let mut out = String::new();
    doc_lines(&e.doc, &mut out);
    out.push_str(
        "#[derive(serde::Serialize, serde::Deserialize, Clone, Debug, PartialEq, Default)]\n",
    );
    let _ = writeln!(out, "pub enum {} {{", e.name);
    for (i, v) in e.variants.iter().enumerate() {
        doc_lines(&v.doc, &mut out);
        if i == e.default_variant {
            out.push_str("    #[default]\n");
        }
        if let Some(r) = &v.rename {
            let _ = writeln!(out, "    #[serde(rename = \"{r}\")]");
        }
        let _ = writeln!(out, "    {},", v.rust_name);
    }
    out.push_str("}\n\n");
    let _ = writeln!(
        out,
        "static_assertions::assert_impl_all!({}: serde::Serialize, serde::de::DeserializeOwned, Clone, core::fmt::Debug, PartialEq, Default);\n",
        e.name
    );
    out
}

fn write_version_mod(model: &IrModel, out_dir: &Path) -> Result<()> {
    let body = format!(
        "{GENERATED_HEADER}//! # Implementation of the OCPP {ver} Specification\n//!\n//! Generated from the official OCPP JSON schemas.\n\n/// datatypes\npub mod datatypes;\n\n/// enumerations\npub mod enumerations;\n\n/// messages\npub mod messages;\n\n/// helper functions\npub mod helpers;\n",
        ver = model.version
    );
    std::fs::write(out_dir.join("mod.rs"), body)?;
    Ok(())
}

fn write_helpers(model: &IrModel, dir: &Path) -> Result<()> {
    std::fs::write(
        dir.join("mod.rs"),
        format!("{GENERATED_HEADER}pub mod datetime_rfc3339;\npub mod validator;\n"),
    )?;
    std::fs::write(
        dir.join("datetime_rfc3339.rs"),
        format!("{GENERATED_HEADER}{DATETIME_TEMPLATE}"),
    )?;
    std::fs::write(dir.join("validator.rs"), render_validator(model))?;
    Ok(())
}

fn render_validator(model: &IrModel) -> String {
    let mut s = String::from(GENERATED_HEADER);
    if !model.decimal_ranges.is_empty() {
        s.push_str("use rust_decimal::Decimal;\n");
    }
    s.push_str(VALIDATOR_IDENTIFIER_TEMPLATE);
    for r in &model.decimal_ranges {
        let mut body = String::new();
        let _ = writeln!(
            body,
            "\n/// Validates that a Decimal lies within the schema-declared range."
        );
        let _ = writeln!(
            body,
            "pub fn {}(value: &Decimal) -> Result<(), ValidationError> {{",
            r.fn_name
        );
        if let Some(min) = r.min {
            let _ = writeln!(body, "    let min = Decimal::try_from({min}_f64).unwrap();");
            let _ = writeln!(body, "    if *value < min {{");
            let _ = writeln!(
                body,
                "        return Err(ValidationError::new(\"value below minimum\"));"
            );
            let _ = writeln!(body, "    }}");
        }
        if let Some(max) = r.max {
            let _ = writeln!(body, "    let max = Decimal::try_from({max}_f64).unwrap();");
            let _ = writeln!(body, "    if *value > max {{");
            let _ = writeln!(
                body,
                "        return Err(ValidationError::new(\"value above maximum\"));"
            );
            let _ = writeln!(body, "    }}");
        }
        let _ = writeln!(body, "    Ok(())");
        let _ = writeln!(body, "}}");
        s.push_str(&body);
    }
    s
}

const DATETIME_TEMPLATE: &str = r#"use chrono::{DateTime, SecondsFormat, Utc};
use serde::{Deserialize, Deserializer, Serializer};

pub fn serialize<S>(date: &DateTime<Utc>, serializer: S) -> Result<S::Ok, S::Error>
where
    S: Serializer,
{
    serializer.serialize_str(&date.to_rfc3339_opts(SecondsFormat::Secs, true))
}

pub fn deserialize<'de, D>(deserializer: D) -> Result<DateTime<Utc>, D::Error>
where
    D: Deserializer<'de>,
{
    let s: String = Deserialize::deserialize(deserializer)?;
    DateTime::parse_from_rfc3339(&s)
        .map(|dt| dt.with_timezone(&Utc))
        .map_err(serde::de::Error::custom)
}

pub mod option {
    use chrono::{DateTime, SecondsFormat, Utc};
    use serde::{self, Deserialize, Deserializer, Serializer};

    pub fn serialize<S>(date: &Option<DateTime<Utc>>, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        match date {
            Some(dt) => serializer.serialize_str(&dt.to_rfc3339_opts(SecondsFormat::Secs, true)),
            None => serializer.serialize_none(),
        }
    }

    pub fn deserialize<'de, D>(deserializer: D) -> Result<Option<DateTime<Utc>>, D::Error>
    where
        D: Deserializer<'de>,
    {
        let opt = Option::<String>::deserialize(deserializer)?;
        match opt {
            Some(s) => DateTime::parse_from_rfc3339(&s)
                .map(|dt| Some(dt.with_timezone(&Utc)))
                .map_err(serde::de::Error::custom),
            None => Ok(None),
        }
    }
}
"#;

const VALIDATOR_IDENTIFIER_TEMPLATE: &str = r#"use std::sync::OnceLock;

use regex::Regex;
use validator::ValidationError;

static REGEX: OnceLock<Regex> = OnceLock::new();

/// Helper function to validate identifierString.
///
/// # identifierString
/// This is a case-insensitive dataType and can only contain characters from the
/// following character set: `a-z`, `A-Z`, `0-9`, `'*'`, `'-'`, `'_'`, `'='`,
/// `':'`, `'+'`, `'|'`, `'@'`, `'.'`
pub fn validate_identifier_string(s: &str) -> Result<(), ValidationError> {
    let res = REGEX
        .get_or_init(|| Regex::new(r"^[a-zA-Z0-9*+=:|@._-]*$").unwrap())
        .is_match(s);

    match res {
        true => Ok(()),
        false => Err(ValidationError::new("Not a valid identifierString")),
    }
}
"#;
